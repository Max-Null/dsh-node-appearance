/**
 * 目标文本的**展示层**折行。
 *
 * 目标常常是一整段长句，里面用 `①` `②` `③` 这类圈号列出条目 —— 数据里没有
 * 换行，于是读起来就是一大坨（截图上那段 200 多字的目标就是如此）。这里只在
 * 渲染前插换行：**不改动任何会话数据**，卡片拿到的仍是原文，复制出去也还是原文。
 *
 * 判据刻意取得简单：只认 Unicode 的圈号 `U+2460`–`U+2473`（`①`–`⑳`），在它
 * 前面断行。中文语境里圈号基本只作列表项标记，「句中偶然出现圈号」的代价是
 * 多折一行；反过来若加上「前导必须是分号/句号」之类的条件，遇到 `③ 源码…`
 * 紧跟在没有标点的分条后就漏断了 —— 两害相权，取简单那条。
 */

/** 圈号 `①`–`⑳` 在 Unicode 里是连续区段。 */
const CIRCLED_NUMBER = /[ \t]*(?=[\u2460-\u2473])/g

/**
 * 把目标的编号分条拆成多行。
 * @param text - 目标原文。
 * @returns 分条处带换行的文本；没有圈号时**逐字返回原串**。
 */
export function objectiveLines(text: string): string {
  if (!/[\u2460-\u2473]/.test(text)) return text
  return text
    .replace(CIRCLED_NUMBER, '\n')
    .replace(/\n{2,}/g, '\n')
    .replace(/^\n+/, '')
}
